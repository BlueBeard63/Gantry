package main

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

var (
	packageRe = regexp.MustCompile(`(?m)^package\s+(\w+)`)
	pageVarRe = regexp.MustCompile(`(?m)^var\s+Page\s*=`)
	compVarRe = regexp.MustCompile(`(?m)^var\s+Component\s*=`)
	moduleRe  = regexp.MustCompile(`(?m)^module\s+(\S+)`)
)

// cmdGen regenerates gantry_registry.go by hand; dev and build do it
// automatically.
func cmdGen(args []string) error {
	appDir, _, err := findApp()
	if err != nil {
		return err
	}
	return writeRegistry(appDir)
}

type registryEntry struct {
	alias      string
	importPath string
	varName    string // "Page" or "Component"
}

// writeRegistry scans pages/, components/ and layouts/ for Go halves
// exporting the conventional Page/Component vars and generates
// gantry_registry.go, so main.go never lists pairs by hand:
//
//	app := ui.NewApp(gantryPairs()...)
func writeRegistry(appDir string) error {
	modData, err := os.ReadFile(filepath.Join(appDir, "go.mod"))
	if err != nil {
		return fmt.Errorf("reading go.mod: %w", err)
	}
	m := moduleRe.FindSubmatch(modData)
	if m == nil {
		return fmt.Errorf("no module line in go.mod")
	}
	module := strings.Trim(string(m[1]), `"`)

	var entries []registryEntry
	for _, kind := range []string{"pages", "components", "layouts"} {
		dir := filepath.Join(appDir, kind)
		items, err := os.ReadDir(dir)
		if err != nil {
			continue // the kind's folder is optional
		}
		names := make([]string, 0, len(items))
		for _, it := range items {
			if it.IsDir() {
				names = append(names, it.Name())
			}
		}
		sort.Strings(names)
		for _, name := range names {
			varName, ok := scanPair(filepath.Join(dir, name))
			if !ok {
				continue // tsx-only pair: nothing to register
			}
			entries = append(entries, registryEntry{
				alias:      kind[:1] + "_" + sanitizeIdent(name),
				importPath: module + "/" + kind + "/" + name,
				varName:    varName,
			})
		}
	}

	var b strings.Builder
	b.WriteString("// Code generated by gantry gen; DO NOT EDIT.\n")
	b.WriteString("// Regenerated by gantry dev/build/gen from the pages/, components/\n")
	b.WriteString("// and layouts/ folders - add a pair and it registers itself.\n\n")
	b.WriteString("package main\n\n")
	if len(entries) > 0 {
		b.WriteString("import (\n")
		for _, e := range entries {
			fmt.Fprintf(&b, "\t%s %q\n", e.alias, e.importPath)
		}
		b.WriteString(")\n\n")
	}
	b.WriteString("// gantryPairs returns every registered Page and Component.\n")
	b.WriteString("func gantryPairs() []any {\n")
	if len(entries) == 0 {
		b.WriteString("\treturn nil\n")
	} else {
		b.WriteString("\treturn []any{\n")
		for _, e := range entries {
			fmt.Fprintf(&b, "\t\t%s.%s,\n", e.alias, e.varName)
		}
		b.WriteString("\t}\n")
	}
	b.WriteString("}\n")
	return os.WriteFile(filepath.Join(appDir, "gantry_registry.go"), []byte(b.String()), 0o644)
}

// scanPair looks at every .go file in a pair folder for the exported
// registration var. Returns which one it found.
func scanPair(dir string) (varName string, ok bool) {
	items, err := os.ReadDir(dir)
	if err != nil {
		return "", false
	}
	for _, it := range items {
		if it.IsDir() || !strings.HasSuffix(it.Name(), ".go") || strings.HasSuffix(it.Name(), "_test.go") {
			continue
		}
		data, err := os.ReadFile(filepath.Join(dir, it.Name()))
		if err != nil {
			continue
		}
		if pageVarRe.Match(data) {
			return "Page", true
		}
		if compVarRe.Match(data) {
			return "Component", true
		}
	}
	return "", false
}

func sanitizeIdent(s string) string {
	out := make([]rune, 0, len(s))
	for _, r := range s {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9':
			out = append(out, r)
		default:
			out = append(out, '_')
		}
	}
	return string(out)
}
